export const FOODS: Food[] = R.map(([name, unit, kcal, carbs, protein, cat, gi]) => ({ name, unit, kcal, carbs, protein, cat, gi }));
export const FOOD_CATS = Array.from(new Set(FOODS.map(f => f.cat)));

export function searchFoods(q: string, extra: Food[] = []): Food[] {
  const s = q.trim().toLowerCase();
  const all = [...extra, ...FOODS];
  if (!s) return all.slice(0, 40);
  const words = s.split(/\s+/);
  return all
    .map(f => {
      const n = (f.name + ' ' + (TA[f.name] ?? '')).toLowerCase();
      if (!words.every(w => n.includes(w) || f.cat.toLowerCase().includes(w) || (TA[f.cat] ?? '').includes(w))) return null;
      return { f, score: n.startsWith(s) ? 0 : n.includes(s) ? 1 : 2 };
    })
    .filter(Boolean)
    .sort((a, b) => a!.score - b!.score)
    .slice(0, 60)
    .map(x => x!.f);
}

/** Packaged-food lookup via Open Food Facts (free, no key). Values per 100 g. */
export async function searchOpenFoodFacts(q: string): Promise<Food[]> {
  const url = `https://world.openfoodfacts.org/cgi/search.pl?search_terms=${encodeURIComponent(q)}&search_simple=1&action=process&json=1&page_size=15&fields=product_name,brands,nutriments`;
  const r = await fetch(url);
  if (!r.ok) throw new Error('Food search is unavailable right now');
  const j = await r.json();
  return (j.products ?? [])
    .filter((p: any) => p.product_name && p.nutriments?.['energy-kcal_100g'])
    .map((p: any) => ({
      name: `${p.product_name}${p.brands ? ` (${String(p.brands).split(',')[0]})` : ''}`,
      unit: '100 g',
      kcal: Math.round(p.nutriments['energy-kcal_100g']),
      carbs: Math.round((p.nutriments.carbohydrates_100g ?? 0) * 10) / 10,
      protein: Math.round((p.nutriments.proteins_100g ?? 0) * 10) / 10,
      cat: 'Packaged',
    }));
}
